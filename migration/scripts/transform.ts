/**
 * Transform: extracted snapshot → transformed/import.ndjson, reports/quality.md
 * and the web app's legacy redirect list. Runs offline except for the image
 * availability check, whose results are cached in transformed/url-status.json.
 */
import { existsSync, readFileSync } from "node:fs"
import { mkdir, writeFile } from "node:fs/promises"
import { join } from "node:path"

import { pickDatasets } from "../mappings/datasets"
import { build, type BuildInput, type Doc } from "./build"
import { checkUrls, ImageRegistry, type UrlFixes, type UrlStatus } from "./lib/images"
import type { Literal } from "./lib/literals"
import { latestExtract, MAPPINGS_DIR, REPO_ROOT, REPORTS_DIR, TRANSFORMED_DIR } from "./lib/paths"
import { Report } from "./lib/report"

/** Write order: referenced documents before the documents that reference them. */
const TYPE_ORDER = ["resort", "room", "eventVenue", "diningVenue", "experience", "spaTreatment", "eventPackage", "offer", "page", "siteSettings", "homePage"]

const readJson = <T>(path: string): T => JSON.parse(readFileSync(path, "utf8")) as T

/** The home page's meta description, which the old site sets at runtime (react-helmet). */
function siteDescription(bundle: string): string {
  const match = bundle.match(/\{name:"description",content:"(Kuriftu Resort & Spa [^"]+)"\}/)
  if (!match) throw new Error("Bundle has no home meta description")
  return JSON.parse(`"${match[1]}"`) as string
}

async function main() {
  const folder = latestExtract()
  const source = readJson<{ origin: string; bundlePath: string; fetchedAt: string }>(join(folder, "source.json"))
  const literals = readJson<Literal[]>(join(folder, "literals.json"))
  const input: BuildInput = {
    ds: pickDatasets(literals),
    hints: readJson(join(MAPPINGS_DIR, "resort-hints.json")),
    categories: readJson(join(MAPPINGS_DIR, "categories.json")),
    home: readJson(join(MAPPINGS_DIR, "home.json")),
    meta: {
      siteDescription: siteDescription(readFileSync(join(folder, "bundle.js"), "utf8")),
      // Brand copy from the approved design reference.
      brandName: "Kuriftu Resorts & Spa",
      footerTagline: "More than a destination. A feeling.",
    },
  }
  const altOverrides = readJson<Record<string, string>>(join(MAPPINGS_DIR, "alt-text.json"))
  const fixes = readJson<UrlFixes>(join(MAPPINGS_DIR, "url-fixes.json"))

  // Pass 1 collects image URLs; check the ones not cached yet.
  await mkdir(TRANSFORMED_DIR, { recursive: true })
  const statusPath = join(TRANSFORMED_DIR, "url-status.json")
  const status: UrlStatus = existsSync(statusPath) ? readJson(statusPath) : {}
  const probe = new ImageRegistry({}, altOverrides, new Report(), true, fixes)
  build(input, probe, new Report())
  await checkUrls(probe.requested, status)
  await writeFile(statusPath, JSON.stringify(sortKeys(status), null, 1))

  // Pass 2 builds the real documents.
  const report = new Report()
  const { docs, redirects } = build(input, new ImageRegistry(status, altOverrides, report, false, fixes), report)

  const ids = new Set<string>()
  for (const doc of docs) {
    if (ids.has(doc._id)) throw new Error(`Duplicate _id ${doc._id}`)
    ids.add(doc._id)
  }
  const sorted = [...docs].sort((a, b) => TYPE_ORDER.indexOf(a._type) - TYPE_ORDER.indexOf(b._type) || a._id.localeCompare(b._id))
  await writeFile(join(TRANSFORMED_DIR, "import.ndjson"), sorted.map((d) => JSON.stringify(d)).join("\n") + "\n")

  const counts = countByType(sorted)
  await writeFile(join(TRANSFORMED_DIR, "counts.json"), JSON.stringify(counts, null, 2))
  await mkdir(REPORTS_DIR, { recursive: true })
  await writeFile(
    join(REPORTS_DIR, "quality.md"),
    report.render({ source: `${source.origin}${source.bundlePath} (fetched ${source.fetchedAt.slice(0, 10)})`, counts, redirects }),
  )
  await writeRedirects(redirects)

  const assets = new Set(sorted.flatMap((d) => JSON.stringify(d).match(/image@[^"]+/g) ?? []))
  console.log(`Transformed ${sorted.length} documents, ${assets.size} images, ${redirects.length} redirects.`)
  console.table(counts)
  console.log(`Contextual alt text: ${report.contextualAltCount}. See reports/quality.md.`)
}

function countByType(docs: Doc[]): Record<string, number> {
  const counts: Record<string, number> = {}
  for (const doc of docs) counts[doc._type] = (counts[doc._type] ?? 0) + 1
  return counts
}

function sortKeys<T extends Record<string, unknown>>(obj: T): T {
  return Object.fromEntries(Object.entries(obj).sort(([a], [b]) => a.localeCompare(b))) as T
}

async function writeRedirects(redirects: { source: string; destination: string }[]) {
  const body = [
    "// Generated by migration/scripts/transform.ts. Do not edit by hand; rerun the transform.",
    "// Permanent redirects from kurifturesorts.com paths to this site. Order matters: specific rules come first.",
    "",
    "export interface LegacyRedirect {",
    "  source: string",
    "  destination: string",
    "}",
    "",
    "export const legacyRedirects: LegacyRedirect[] = [",
    ...redirects.map((r) => `  { source: ${JSON.stringify(r.source)}, destination: ${JSON.stringify(r.destination)} },`),
    "]",
    "",
  ].join("\n")
  const dir = join(REPO_ROOT, "lib", "redirects")
  await mkdir(dir, { recursive: true })
  await writeFile(join(dir, "legacy.ts"), body)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
